let currentPage = 1;
let totalPages = Math.ceil(Object.keys(damageSkinMapping).length / PAGE_SIZE);

let selectedSkinId = null;

function start() {
    showPageSelection();
}

function showPageSelection() {
    let str = "Welcome to the Damage Skin store, feel free to browse!: \r\n";

    let pageSelectionStr = "";
    for (let i = 1; i <= totalPages; i++) {
        pageSelectionStr += "#L" + (100000 + i) + "##rPage " + i + "#l";
        if (i % 5 === 0) {
            pageSelectionStr += "\r\n";
        }
    }

    str += pageSelectionStr + "\r\n";
    cm.sendSimple(str);
}

function showPage(page) {
    let str = "Select a damage skin (Page " + page + " of " + totalPages + "):\r\n";
    str += "\r\n";

    const sortedKeys = Object.keys(damageSkinMapping).map(Number).sort((a, b) => a - b);
    const start = (page - 1) * PAGE_SIZE;
    const end = Math.min(start + PAGE_SIZE, sortedKeys.length);

    for (let i = start; i < end; i++) {
        const damageSkinId = sortedKeys[i];
        str += "#L" + damageSkinId + "##fEffect/DamageSkin.img/" + damageSkinMapping[damageSkinId] + "/NoRed0/7##l   ";
        if ((i + 1) % 5 === 0) {
            str += "\r\n";
        }
    }

    str += "\r\n";
    str += "#L99998#Previous Page#l ";
    str += "#L99999#Next Page#l ";
    str += "\r\n#L100000#Return to Page Selection#l ";

    cm.sendSimple(str);
}

let step = 0;

function action(mode, type, selection) {
    if (mode === 1) {
        if (step === 0) {
            if (selection === 99998) {
                if (currentPage > 1) {
                    currentPage--;
                }
                showPage(currentPage);
            } else if (selection === 99999) {
                if (currentPage < totalPages) {
                    currentPage++;
                }
                showPage(currentPage);
            } else if (selection === 100000) {
                showPageSelection();
            } else if (selection >= 100001 && selection <= (100000 + totalPages)) {
                currentPage = selection - 100000;
                showPage(currentPage);
            } else if (damageSkinMapping.hasOwnProperty(selection)) {
                selectedSkinId = damageSkinMapping[selection];
                if (selectedSkinId !== undefined) {
                    const savedSkins = cm.getPlayer().getSavedDamageSkins();

                    if (savedSkins.includes(selectedSkinId)) {
                        cm.sendOk("You already own this damage skin and cannot purchase it again.");
                        cm.dispose();
                    } else {
                        step = 1;
                        cm.sendSimple("How would you like to purchase this damage skin?\r\n" +
                            "#L1#Use " + CURRENCY_1_QUANTITY + " of \t #i" + CURRENCY_1_ID + ":# #l\r\n" +
                            "#L2#Use " + CURRENCY_2_QUANTITY + " of \t #i" + CURRENCY_2_ID + ":# #l");
                    }
                } else {
                    cm.sendOk("Invalid selection. Please try again.");
                    cm.dispose();
                }
            }
        } else if (step === 1) {
            let itemId = selection === 1 ? CURRENCY_1_ID : CURRENCY_2_ID;
            let itemQuantity = selection === 1 ? CURRENCY_1_QUANTITY : CURRENCY_2_QUANTITY;

            if (cm.haveItem(itemId, itemQuantity)) {
                cm.gainItem(itemId, -itemQuantity);
                cm.getPlayer().setDamageSkin(selectedSkinId, true);
                cm.getPlayer().saveDamageSkinToStorage(selectedSkinId);

                cm.sendOk("Your damage skin has been changed to #b#rSkin ID: #b" + selectedSkinId + " #k. " +
                    "You have been charged " + itemQuantity + " of item #b#r#i" + itemId + ":# #k.");
            } else {
                cm.sendOk("You do not have enough of item  #b#r#i" + itemId + ":# #k  to purchase this skin.");
            }
            cm.dispose();
        }
    } else {
        cm.dispose();
    }
}
