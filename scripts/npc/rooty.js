function handleSubSelection(selection) {
    if (selection >= 2 && selection <= 18) {
        cosmetic = true
        showItemOptions(selection);
    } else if (selection == 19 || selection == 20) {
        status++;
        showMasteryBooks(selection);
    } else if (selection >= 31 && selection <= 34) {
        status++;
        showMapleWeapons(selection);
    } else if (selection >= 71 && selection <= 74) {
        status++;
        showBossWeapons(selection);
    } else if (selection == 41) {
        status++;
        showRootItems(selection);
    }
}

