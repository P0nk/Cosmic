    private static int bandForLevel(int level) {
        int lv = Math.max(1, level);
        return ((lv - 1) / 10 + 1) * 10; // 1..10->10, 11..20->20, ...
    }

    private static JobGroup groupFor(Character chr) {
        if (chr == null) return JobGroup.OTHER;

        Job j = chr.getJob();
        if (chr.getLevel() <= 10 || j == Job.BEGINNER || j == Job.NOBLESSE || j == Job.LEGEND) {
            return JobGroup.BEGINNER;
        }

        // Use job niche: 1=warrior,2=magician,3=bowman,4=thief,5=pirate
        switch (j.getJobNiche()) {
            case 1: return JobGroup.WARRIOR;
            case 2: return JobGroup.MAGE;
            case 3: return JobGroup.ARCHER;
            case 4: return JobGroup.THIEF;
            case 5: return JobGroup.PIRATE;
            default: return JobGroup.OTHER;
        }
    }

    private static int[] poolFor(JobGroup g, int band) {
        NavigableMap<Integer, int[]> m = TABLES.get(g);
        if (m == null || m.isEmpty()) return null;

        int[] exact = m.get(band);
        if (exact != null && exact.length > 0) return exact;

        Map.Entry<Integer, int[]> e = m.floorEntry(band);
        return (e != null) ? e.getValue() : null;
    }

    private static int pickFromPools(int[] mainPool, int[] allPool, int allWeightPercent) {
        if (mainPool == null || mainPool.length == 0) return -1;
        if (allPool == null || allPool.length == 0 || allWeightPercent <= 0) {
            return mainPool[RNG.nextInt(mainPool.length)];
        }
        boolean useAll = RNG.nextInt(100) < allWeightPercent;
        int[] p = useAll ? allPool : mainPool;
        return p[RNG.nextInt(p.length)];
    }

    /** Drops N weapons based on min(playerBand, mobBand) and player's job group. */
    public static void dropForMonster(
            MapleMap map,
            Monster mob,
            Character owner,
            Point seedPos,
            int rolls,
            byte dropType,
            boolean playerDrop
    ) {
        if (map == null || mob == null || owner == null) return;

        JobGroup g = groupFor(owner);
        if (g == JobGroup.OTHER) return;

        int playerBand = bandForLevel(owner.getLevel());
        int mobBand = bandForLevel(mob.getLevel());
        int band = Math.min(playerBand, mobBand);

        int[] mainPool = poolFor(g, band);
        if (mainPool == null || mainPool.length == 0) return;

        // Beginner: use only BEGINNER pool (avoid all-jobs pool unless you explicitly want it)
        int[] allPool = null;
        int allWeight = 0;
        if (g != JobGroup.BEGINNER) {
            allPool = poolFor(JobGroup.ALL, band);
            allWeight = ALL_POOL_WEIGHT_PERCENT;
        }

        int dropRate = Math.max(1, YamlConfig.config.worlds.get(0).drop_rate);
        int chance = BASE_CHANCE * dropRate;
        if (chance > ROLL_RANGE) chance = ROLL_RANGE;

        rolls = Math.max(1, rolls);
        for (int i = 0; i < rolls; i++) {
            int roll = RNG.nextInt(ROLL_RANGE) + 1;
            if (roll > chance) continue;

            int itemId = pickFromPools(mainPool, allPool, allWeight);
            if (itemId <= 0) continue;

            Item item = new Item(itemId, (short) 0, (short) 1);
            map.spawnItemDrop((MapObject) mob, owner, item, seedPos, dropType, playerDrop);
        }
    }

    /** Convenience overload with sensible defaults. */
    public static void dropForMonster(MapleMap map, Monster mob, Character owner) {
        byte dropType = (byte) (owner.getParty() != null ? 1 : 0);
        dropForMonster(map, mob, owner, mob.getPosition(), 1, dropType, false);
    }
